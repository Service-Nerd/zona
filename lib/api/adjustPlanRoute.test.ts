/**
 * Minimal PostgREST double, widened from `generatePlanRoute.test.ts`'s for this route's
 * chains: it adds `is`, `in`, `or`, `order`, `limit`, `gte`, `lt`, `single` and `upsert`.
 *
 * ⚠️ IT IS STRICT ON PURPOSE. `or()` understands only the one disjunction this route
 * gives it and THROWS on anything else, and `single()` reproduces real PostgREST by
 * returning an error on no rows. A permissive double is worse than none: it admits rows
 * the real query excludes and every arm above it goes green against a database ignoring
 * its own filters. Arm A proves it positively rather than trusting these fifteen arms.
 */
function fakeTable(name: string) {
  const rows = () => (S.store[name] ??= [])
  const eqs: [string, unknown][] = []
  const isNull: string[] = []
  const ins: [string, unknown[]][] = []
  const ranges: [string, 'gte' | 'lt', string][] = []
  /** Column names where at least one must be non-null. */
  let orNotNull: string[] | null = null
  let mode: 'select' | 'insert' | 'update' | 'upsert' | 'delete' = 'select'
  let head = false
  let limitN: number | null = null
  let order: [string, boolean] | null = null
  let payload: Record<string, unknown> | null = null

  const matching = () => {
    let m = rows().filter(r =>
      eqs.every(([c, v]) => r[c] === v) &&
      isNull.every(c => r[c] == null) &&
      ins.every(([c, vs]) => vs.includes(r[c])) &&
      ranges.every(([c, op, v]) =>
        op === 'gte' ? String(r[c]) >= v : String(r[c]) < v) &&
      (!orNotNull || orNotNull.some(c => r[c] != null)))
    if (order) {
      const [col, asc] = order
      m = m.slice().sort((a, b) => {
        const x = a[col] as string | number, y = b[col] as string | number
        return (x > y ? 1 : x < y ? -1 : 0) * (asc ? 1 : -1)
      })
    }
    return limitN == null ? m : m.slice(0, limitN)
  }

  const result = () => {
    if (mode === 'insert' || mode === 'upsert') {
      if (name === 'plan_adjustments' && S.failAdjustmentInsert) {
        return { data: null, error: { message: 'insert failed' }, count: 0 }
      }
      if (name === 'plans' && S.failPlanWrite) {
        return { data: null, error: { message: 'new row violates row-level security policy for table "plans"' }, count: 0 }
      }
      if (mode === 'upsert') {
        const i = rows().findIndex(r => eqs.every(([c, v]) => r[c] === v) || r.user_id === payload!.user_id)
        if (i >= 0) { Object.assign(rows()[i], payload); return { data: [rows()[i]], error: null, count: 1 } }
      }
      rows().push({ ...payload })
      return { data: [rows()[rows().length - 1]], error: null, count: 1 }
    }
    if (mode === 'update') {
      const hit = matching()
      for (const r of hit) Object.assign(r, payload)
      return { data: hit, error: null, count: hit.length }
    }
    if (mode === 'delete') {
      const hit = matching()
      S.store[name] = rows().filter(r => !hit.includes(r))
      return { data: null, error: null, count: hit.length }
    }
    if (name === 'strava_activities' && S.failActivityRead) throw new Error('activity log unreachable')
    const m = matching()
    return { data: head ? null : m, count: m.length, error: null }
  }

  const api: Record<string, unknown> = {
    select: (_c?: string, o?: { head?: boolean }) => {
      if (mode === 'select') head = !!o?.head
      return api
    },
    insert: (row: Record<string, unknown>) => { mode = 'insert'; payload = row; return api },
    upsert: (row: Record<string, unknown>) => { mode = 'upsert'; payload = row; return api },
    update: (row: Record<string, unknown>) => { mode = 'update'; payload = row; return api },
    delete: () => { mode = 'delete'; return api },
    eq: (c: string, v: unknown) => { eqs.push([c, v]); return api },
    is: (c: string, v: unknown) => {
      if (v !== null) throw new Error(`fake .is(${c}, ${String(v)}) — only null is modelled`)
      isNull.push(c); return api
    },
    in: (c: string, vs: unknown[]) => { ins.push([c, vs]); return api },
    or: (expr: string) => {
      // Only `a.not.is.null,b.not.is.null`. Anything else and the double would be
      // silently admitting rows the real query excludes.
      const cols = expr.split(',').map(p => {
        const m = /^([a-z_]+)\.not\.is\.null$/.exec(p.trim())
        if (!m) throw new Error(`fake .or() cannot model "${p}" — widen it deliberately`)
        return m[1]
      })
      orNotNull = cols; return api
    },
    gte: (c: string, v: string) => { ranges.push([c, 'gte', v]); return api },
    lt:  (c: string, v: string) => { ranges.push([c, 'lt',  v]); return api },
    order: (c: string, o?: { ascending?: boolean }) => { order = [c, o?.ascending !== false]; return api },
    limit: (n: number) => { limitN = n; return api },
    single: () => {
      const r = result()
      const d = r.data as Record<string, unknown>[] | null
      // Real `single()` errors on 0 rows — the route's 404 depends on `data?.plan_json`
      // being absent, so returning null data with an error is the honest shape.
      if (!d || d.length === 0) return Promise.resolve({ data: null, error: { message: 'no rows' }, count: 0 })
      return Promise.resolve({ ...r, data: d[0] })
    },
    maybeSingle: () => {
      const r = result()
      const d = r.data as Record<string, unknown>[] | null
      if (d && d.length > 1) return Promise.resolve({ data: null, error: { message: 'multiple rows returned' } })
      return Promise.resolve({ ...r, data: d?.[0] ?? null })
    },
    then: (res: (v: unknown) => unknown, rej?: (e: unknown) => unknown) => {
      try { return Promise.resolve(result()).then(res, rej) } catch (e) { return Promise.reject(e).then(res, rej) }
    },
  }
  return api
}

